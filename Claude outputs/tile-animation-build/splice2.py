# the generic tiles block replaces the Asteroids block
a = s.index("\t/* ---- opt:AST  live Asteroids scene (JS part) ---- */")
b = s.index("\t/* ---- /opt:AST ---- */") + len("\t/* ---- /opt:AST ---- */")
tiles_js = r'''	/* ---- opt:TILES  live scenes (JS part): one mechanism for every tile ----
	   A scene is a <template class="tl-tpl"> keyed by the tile's image file. It is cloned into
	   the tile's zoom layer, so the hover-zoom modes still apply to it. Entry modes:
	   css (the entry runs from CSS on section.pv-in), play (the entry is one play cycle),
	   ast (the Asteroids scene, which holds its opening frame with tl-ready), none (a loop).
	   The play cycle is the class tl-play on the scene for data-cycle seconds, scaled by
	   the speed setting; a scene that needs script during the cycle registers a hook. */
	var TILES = {}, TILE_KEYS = [];
	var HOOKS = {
		ast: {
			start: function (t) { t.score = 90; t.scoreEl = t.scene.querySelector(".ast-score"); },
			play: function (t, ms) {
				t.hits.forEach(function (h) { t.timers.push(setTimeout(function () { t.score += 10; t.scoreEl.textContent = t.score; }, ms * h)); });
			},
			reset: function (t) { t.score = 90; t.scoreEl.textContent = t.score; }
		},
		pbi: {
			start: function (t) { t.numEl = t.scene.querySelector(".pbi-num"); },
			play: function (t, ms) {
				var el = t.numEl, t0 = ms * 0.08, dur = ms * 0.5, start = null;
				function frame(now) {
					if (start === null) start = now;
					var p = Math.min(1, (now - start) / dur);
					var v = 7.16 * (1 - Math.pow(1 - p, 3));
					el.textContent = "€ " + v.toFixed(2) + "bn";
					if (p < 1 && t.scene.classList.contains("tl-play")) requestAnimationFrame(frame);
				}
				t.timers.push(setTimeout(function () { requestAnimationFrame(frame); }, t0));
			},
			reset: function (t) { t.numEl.textContent = "€ 0.00bn"; }
		}
	};
	Array.prototype.forEach.call(document.querySelectorAll("template.tl-tpl"), function (tpl) {
		var file = tpl.getAttribute("data-for");
		var sec = sections.filter(function (x) { return x._pv && x._pv.file === file; })[0];
		if (!sec) return;
		var zoom = sec._pv.a.querySelector(".pv-zoom");
		zoom.appendChild(tpl.content.cloneNode(true));
		var all = zoom.querySelectorAll(".tl-scene");
		var t = {
			key: tpl.getAttribute("data-key"), sec: sec, zoom: zoom, scene: all[all.length - 1],
			kind: tpl.getAttribute("data-kind"), label: tpl.getAttribute("data-label"),
			entry: tpl.getAttribute("data-entry"), cycle: parseFloat(tpl.getAttribute("data-cycle")) || 0,
			entryLen: parseFloat(tpl.getAttribute("data-entry-len")) || 0,
			autoplay: tpl.getAttribute("data-autoplay") === "1",
			hits: (tpl.getAttribute("data-hits") || "").split(",").map(parseFloat).filter(function (n) { return n > 0; }),
			timers: [], timer: 0, hovering: false
		};
		TILES[t.key] = t; TILE_KEYS.push(t.key);
		if (HOOKS[t.key] && HOOKS[t.key].start) HOOKS[t.key].start(t);
		if (canHover) {
			sec.addEventListener("mouseenter", function () { t.hovering = true; tilePlay(t); });
			sec.addEventListener("mouseleave", function () { t.hovering = false; });
		}
		sec.addEventListener("focusin", function () { t.hovering = true; tilePlay(t); });
		sec.addEventListener("focusout", function () { t.hovering = false; });
		if (!canHover) {
			new IntersectionObserver(function (en) { if (en[0].isIntersecting) tilePlay(t); },
				{ rootMargin: "-35% 0px -35% 0px" }).observe(sec);
		}
	});
	function tileOn(t) { return !!state.live[t.key] && !state.rm; }
	function tilePlay(t) {
		if (!tileOn(t) || t.cycle <= 0 || t.scene.classList.contains("tl-play")) return;
		if (t.entry === "ast" && !t.scene.classList.contains("tl-ready")) return;
		t.scene.classList.add("tl-play");
		var ms = t.cycle * SPEED[state.speed].k * 1000;
		clearTimeout(t.timer);
		t.timer = setTimeout(function () {
			t.scene.classList.remove("tl-play");
			if (t.hovering) { void t.scene.offsetWidth; tilePlay(t); }
		}, ms);
		if (HOOKS[t.key] && HOOKS[t.key].play) HOOKS[t.key].play(t, ms);
	}
	// called when a tile first scrolls into view (pv-in)
	function tileEnter(sec) {
		TILE_KEYS.forEach(function (k) {
			var t = TILES[k];
			if (t.sec !== sec || !tileOn(t)) return;
			if (t.entry === "play") { tilePlay(t); return; }
			if (t.entry === "none") return;
			var ms = (state.rm ? 0 : t.entryLen * SPEED[state.speed].k * 1000) + 150;
			t.timers.push(setTimeout(function () {
				t.scene.classList.add("tl-ready");
				if (t.autoplay) setTimeout(function () { tilePlay(t); }, 250);
			}, ms));
		});
	}
	function tileReset(t) {
		clearTimeout(t.timer); t.timers.forEach(clearTimeout); t.timers = [];
		t.scene.classList.remove("tl-play", "tl-ready");
		if (HOOKS[t.key] && HOOKS[t.key].reset) HOOKS[t.key].reset(t);
	}
	function applyLive() {
		TILE_KEYS.forEach(function (k) {
			var t = TILES[k], on = !!state.live[k];
			t.scene.hidden = !on;
			t.zoom.classList.toggle("tl-hidepic", on && t.kind === "redraw");
			if (!on) tileReset(t);
		});
		Array.prototype.forEach.call(bar.querySelectorAll("[data-tile]"), function (b) {
			b.setAttribute("aria-checked", state.live[b.getAttribute("data-tile")] ? "true" : "false");
		});
	}
	(function initLive() {
		var on = TILE_KEYS.slice();
		if (state.liveFromUrl !== undefined) on = state.liveFromUrl === "all" ? TILE_KEYS.slice() : state.liveFromUrl.split(",").filter(Boolean);
		TILE_KEYS.forEach(function (k) { state.live[k] = on.indexOf(k) >= 0; });
	})();
	/* ---- /opt:TILES ---- */'''
