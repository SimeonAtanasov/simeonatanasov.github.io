"""Live files for the home page (HOME-01) from the preview build.

Reads tiles_css.txt and tiles_tpl.txt (written by tiles_build.py) and writes
  out/assets/css/home-tiles.css   the scene rules, keyed to the live page
  out/assets/js/home-tiles.js     the runtime with the nine scenes embedded as strings
The preview page keeps its own copy of the same rules (splice2.py); the differences
are the selector for the entry (section.tl-in instead of section.pv-in), the speed
(fixed at normal) and reduced motion (the media query instead of body.pv-rm).
Run tiles_build.py first, then this, then apply_home_tiles.py for index.html."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
css = open(os.path.join(HERE, "tiles_css.txt"), encoding="utf-8").read()
tpl = open(os.path.join(HERE, "tiles_tpl.txt"), encoding="utf-8").read()
meta = json.load(open(os.path.join(HERE, "tiles_meta.json"), encoding="utf-8"))

def must(cond, msg):
    if not cond:
        raise SystemExit("live_build: " + msg)

# ---------------------------------------------------------------- CSS
head_old = css[:css.index("/* ---- tile:")]
must("shared layer rules" in head_old, "base block not found")
head_new = """/* Home page tile scenes (HOME-01, 26 October 2026). Generated by
   Claude outputs/tile-animation-build/live_build.py from tiles_build.py; edit the
   generator, not this file. Nine spotlight tiles carry a small animated scene over or
   in place of their image. Only transform and opacity animate (plus a static
   mix-blend-mode on the light overlays). The markup is cloned in by
   assets/js/home-tiles.js; without script nothing here matches anything. */

/* The scene sits inside the tile's image link, under the template's purple veil
   (.image:before), so an inactive tile still looks inactive. isolation keeps the two
   z-indexes local to the link; the chips of the two assessment tiles (.image-tools,
   z-index 2 on the section) stay above both. */
#one.spotlights > section > .image { overflow: hidden; isolation: isolate; }
#one.spotlights > section > .image:before { z-index: 1; }
.tl-scene { position: absolute; top: 0; right: 0; bottom: 0; left: 0; z-index: 0; display: block; pointer-events: none; }
.tl-scene > svg { position: absolute; top: 0; left: 0; width: 100%; height: 100%; display: block; }
.tl-scene svg * { transform-box: fill-box; transform-origin: center; }
/* speed: every scene derives its durations from --tl-k; 1 is the speed the preview
   calls normal */
.tl-scene { --tl-k: 1; }
/* reduced motion: every animation jumps to its end state, so entries show their final
   frame, transient overlays stay invisible and loops stand still; the script starts no
   play cycle either */
@media (prefers-reduced-motion: reduce) {
	.tl-scene, .tl-scene * { animation-duration: 0s !important; animation-delay: 0s !important; }
}

"""
body = css[len(head_old):]
must("pv-" not in body.replace("section.pv-in", ""), "preview-only selector in the scene rules")
body = body.replace("section.pv-in ", "section.tl-in ")
must("pv-" not in body, "pv- left in the scene rules")
css_live = head_new + body
must("\u2014" not in css_live, "em dash in css")
must("\r" not in css_live, "CR in css")

# ---------------------------------------------------------------- JS
lines = [l for l in tpl.split("\n") if l.strip()]
must(len(lines) == 9 and all(l.startswith("<template class=\"tl-tpl\"") for l in lines), "expected nine template lines")
for l in lines:
    must("`" not in l and "\\" not in l and "</script" not in l.lower(), "unsafe character in template markup")
    must(all(ord(c) < 128 for c in l), "non-ascii in template markup")
scenes_js = "\tvar SCENES = [\n" + ",\n".join("\t\t" + json.dumps(l) for l in lines) + "\n\t].join(\"\");\n"

runtime = r'''/* Home page tile scenes (HOME-01, 26 October 2026).
   Nine spotlight tiles on the home page carry a small animated scene over or in place
   of their image: four vector redraws (GDPR readiness, risk matrix, the wave field
   behind the assessment chips, Asteroids), four light overlays traced on the photo
   (scanner, AI Act, digests, fines dashboard) and the Practical Privacy card, one
   cut-out layer of its photo. The markup of the nine scenes is the SCENES array below,
   generated by Claude outputs/tile-animation-build/live_build.py from tiles_build.py;
   edit the generator, not this file. The rules are in assets/css/home-tiles.css. Only
   transform and opacity animate. Nothing is stored and nothing leaves the page.

   How a scene runs. A scene is matched to its tile by the image file name and cloned
   into the tile's image link, under the template's veil. Entry modes:
     css   the entry runs from CSS once the section carries tl-in (readiness, matrix,
           privacy card); the play cycle animates other elements
     play  the entry is one play cycle (scanner, AI Act, digests, fines)
     ast   the Asteroids scene holds its opening frame with tl-ready, then plays once
     none  the wave field, a loop with no entry and no play
   The section gets tl-in when it reaches the middle band of the viewport, the same
   band in which main.js lifts the veil (scrollex, mode middle, -10vh), so the scene
   enters as the tile lights up. A play cycle is the class tl-play on the scene for
   data-cycle seconds; it runs on hover or focus, and on a touch device each time the
   tile reaches mid-screen. With prefers-reduced-motion the stylesheet freezes every
   animation at its end frame and no cycle is started. */
(function () {
	"use strict";
	if (!("IntersectionObserver" in window) || !("content" in document.createElement("template")) || !window.matchMedia) return;
	var one = document.getElementById("one");
	if (!one) return;
__SCENES__
	var RM = window.matchMedia("(prefers-reduced-motion: reduce)");
	var canHover = window.matchMedia("(hover: hover)").matches;
	var HOOKS = {
		ast: {
			start: function (t) { t.score = 90; t.scoreEl = t.scene.querySelector(".ast-score"); },
			play: function (t, ms) {
				/* every cycle is a fresh game: the score starts again at the opening frame's 90 */
				t.score = 90; t.scoreEl.textContent = t.score;
				t.hits.forEach(function (h) { t.timers.push(setTimeout(function () { t.score += 10; t.scoreEl.textContent = t.score; }, ms * h)); });
			}
		},
		pbi: {
			start: function (t) { t.numEl = t.scene.querySelector(".pbi-num"); },
			play: function (t, ms) {
				var el = t.numEl, dur = ms * 0.5, start = null;
				el.textContent = "\u20ac 0.00bn";
				function frame(now) {
					if (start === null) start = now;
					var p = Math.min(1, (now - start) / dur);
					el.textContent = "\u20ac " + (7.16 * (1 - Math.pow(1 - p, 3))).toFixed(2) + "bn";
					if (p < 1 && t.scene.classList.contains("tl-play")) requestAnimationFrame(frame);
				}
				t.timers.push(setTimeout(function () { requestAnimationFrame(frame); }, ms * 0.08));
			}
		}
	};
	var holder = document.createElement("div");
	holder.innerHTML = SCENES;
	var templates = {};
	Array.prototype.forEach.call(holder.querySelectorAll("template.tl-tpl"), function (tpl) {
		templates[tpl.getAttribute("data-for")] = tpl;
	});
	var tiles = [];
	Array.prototype.forEach.call(one.children, function (sec) {
		if (sec.tagName !== "SECTION") return;
		var a = sec.querySelector(".image"), img = a && a.querySelector("img");
		if (!img) return;
		var tpl = templates[(img.getAttribute("src") || "").split("/").pop()];
		if (!tpl) return;
		a.appendChild(tpl.content.cloneNode(true));
		var all = a.querySelectorAll(".tl-scene");
		var t = {
			key: tpl.getAttribute("data-key"), sec: sec, scene: all[all.length - 1],
			entry: tpl.getAttribute("data-entry"), cycle: parseFloat(tpl.getAttribute("data-cycle")) || 0,
			entryLen: parseFloat(tpl.getAttribute("data-entry-len")) || 0,
			autoplay: tpl.getAttribute("data-autoplay") === "1",
			hits: (tpl.getAttribute("data-hits") || "").split(",").map(parseFloat).filter(function (n) { return n > 0; }),
			timers: [], timer: 0, hovering: false, pending: false, entered: false
		};
		tiles.push(t);
		if (HOOKS[t.key] && HOOKS[t.key].start) HOOKS[t.key].start(t);
		if (canHover) {
			sec.addEventListener("mouseenter", function () { t.hovering = true; tilePlay(t); });
			sec.addEventListener("mouseleave", function () { t.hovering = false; });
		}
		sec.addEventListener("focusin", function () { t.hovering = true; tilePlay(t); });
		sec.addEventListener("focusout", function () { t.hovering = false; });
		if (!canHover) {
			new IntersectionObserver(function (en) { if (en[0].isIntersecting) tilePlay(t); },
				{ rootMargin: "-35% 0px -35% 0px" }).observe(sec);
		}
	});
	if (!tiles.length) return;
	/* A hold scene (entry css or ast) is ready once its entry has run; a play asked for
	   before that waits for it. */
	function tileReady(t) { return t.entry === "play" || t.scene.classList.contains("tl-ready"); }
	function tilePlay(t) {
		if (RM.matches || t.cycle <= 0 || t.scene.classList.contains("tl-play")) return;
		if (!t.entered) { t.pending = true; return; }
		if (!tileReady(t)) { t.pending = true; return; }
		t.pending = false;
		t.scene.classList.add("tl-play");
		var ms = t.cycle * 1000;
		clearTimeout(t.timer);
		t.timer = setTimeout(function () {
			t.scene.classList.remove("tl-play");
			if (t.hovering) { void t.scene.offsetWidth; tilePlay(t); }
		}, ms);
		if (HOOKS[t.key] && HOOKS[t.key].play) HOOKS[t.key].play(t, ms);
	}
	function tileEnter(t) {
		t.entered = true;
		t.sec.classList.add("tl-in");
		if (t.entry === "play") { tilePlay(t); return; }
		if (t.entry === "none") return;
		var ms = (RM.matches ? 0 : t.entryLen * 1000) + 150;
		t.timers.push(setTimeout(function () {
			t.scene.classList.add("tl-ready");
			if (t.autoplay || t.pending) setTimeout(function () { tilePlay(t); }, 250);
		}, ms));
	}
	var entryIO = new IntersectionObserver(function (entries) {
		entries.forEach(function (en) {
			if (!en.isIntersecting) return;
			entryIO.unobserve(en.target);
			tiles.forEach(function (t) { if (t.sec === en.target && !t.entered) tileEnter(t); });
		});
	}, { rootMargin: "-40% 0px -40% 0px" });
	/* Arm once the page has loaded, when main.js takes the preload veil off; a tile
	   already in the band then enters as the veil fades rather than under it. */
	function arm() { tiles.forEach(function (t) { entryIO.observe(t.sec); }); }
	if (document.readyState === "complete") setTimeout(arm, 150);
	else window.addEventListener("load", function () { setTimeout(arm, 150); });
})();
'''
js_live = runtime.replace("__SCENES__\n", scenes_js)
must("\u2014" not in js_live, "em dash in js")
must(all(ord(c) < 128 for c in js_live), "non-ascii in js")

os.makedirs(os.path.join(OUT, "assets", "css"), exist_ok=True)
os.makedirs(os.path.join(OUT, "assets", "js"), exist_ok=True)
open(os.path.join(OUT, "assets", "css", "home-tiles.css"), "w", encoding="utf-8", newline="\n").write(css_live)
open(os.path.join(OUT, "assets", "js", "home-tiles.js"), "w", encoding="utf-8", newline="\n").write(js_live)
print("home-tiles.css", len(css_live.encode()), "bytes;", "home-tiles.js", len(js_live.encode()), "bytes;",
      "scenes:", ", ".join(m["key"] for m in meta))
