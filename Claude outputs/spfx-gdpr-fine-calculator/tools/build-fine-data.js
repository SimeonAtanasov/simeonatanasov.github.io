/* Regenerates fineData.ts from the website's calculator-data.js.
 *
 *   node tools/build-fine-data.js <calculator-data.js> <fineData.ts>
 *
 * Both builds are generated from one source on purpose. The alternative is two
 * hand-maintained copies of 357 rows, which drift, and then the web part and
 * the website answer the same question differently and nobody notices for
 * months.
 *
 * The field order is asserted rather than assumed: the tuple type in the output
 * is positional, so a reordered FINE_FIELDS would silently shift every value
 * one column left.
 */

'use strict';

const fs = require('fs');
const vm = require('vm');

const EXPECTED_FIELDS = [
  'etid', 'company', 'country', 'year', 'fine', 'turnover', 'type', 'sector',
  'articles', 'tier', 'conf', 'fin', 'tyear', 'tbasis', 'tsource', 'ep'
];

const inPath = process.argv[2];
const outPath = process.argv[3];

if (!inPath || !outPath) {
  console.error('usage: node tools/build-fine-data.js <calculator-data.js> <fineData.ts>');
  process.exit(1);
}

const src = fs.readFileSync(inPath, 'utf8');

/* calculator-data.js is a plain script of var declarations with no dependencies,
   so it is run in a bare sandbox and the globals are read back out. A sandbox
   rather than eval because this file is strict mode, where eval keeps its own
   scope and the declarations would never appear. */
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(src, sandbox, { filename: inPath });

const FINE_FIELDS = sandbox.FINE_FIELDS;
const FINE_ROWS = sandbox.FINE_ROWS;
const ARTICLE_NAMES = sandbox.ARTICLE_NAMES;
const FINE_TYPES = sandbox.FINE_TYPES;
const FINE_SECTORS = sandbox.FINE_SECTORS;

function fail(message) {
  console.error('build-fine-data: ' + message);
  process.exit(1);
}

if (!Array.isArray(FINE_FIELDS) || FINE_FIELDS.join(',') !== EXPECTED_FIELDS.join(',')) {
  fail('FINE_FIELDS has changed. Update EXPECTED_FIELDS and the FineRow tuple together.\n'
    + '  expected: ' + EXPECTED_FIELDS.join(',') + '\n'
    + '  found:    ' + (FINE_FIELDS || []).join(','));
}
if (!Array.isArray(FINE_ROWS) || !FINE_ROWS.length) { fail('FINE_ROWS is empty'); }
if (!Array.isArray(FINE_TYPES) || !FINE_TYPES.length) { fail('FINE_TYPES is empty'); }
if (!Array.isArray(FINE_SECTORS) || !FINE_SECTORS.length) { fail('FINE_SECTORS is empty'); }
if (!ARTICLE_NAMES || !Object.keys(ARTICLE_NAMES).length) { fail('ARTICLE_NAMES is empty'); }

FINE_ROWS.forEach(function (r, i) {
  if (r.length !== EXPECTED_FIELDS.length) {
    fail('row ' + i + ' has ' + r.length + ' fields, expected ' + EXPECTED_FIELDS.length);
  }
  if (!(r[5] > 0)) { fail('row ' + i + ' (' + r[1] + ') has no usable turnover'); }
  if (!(r[4] > 0)) { fail('row ' + i + ' (' + r[1] + ') has no usable fine'); }
});

const q = function (s) { return JSON.stringify(s); };

let out = '/* GDPR fine benchmark data, bundled with the web part.\n'
  + '\n'
  + '   Fines, dates, sectors, Articles and the violation classification come from the\n'
  + '   GDPR enforcement tracker, by way of the Power BI export of 20 September 2026,\n'
  + '   with the cases that export drops (year-only decision dates) carried over.\n'
  + '   Article names are the model\'s own lookup table.\n'
  + '   Turnover is not in that source: it was researched separately from annual\n'
  + '   reports, statutory filings and national company registers, and each row\n'
  + '   carries a confidence and a source for it.\n'
  + '\n'
  + '   ' + FINE_ROWS.length + ' decisions carry both a fine and a turnover.\n'
  + '\n'
  + '   Generated by tools/build-fine-data.js. Do not hand edit. Regenerate from the\n'
  + '   website\'s calculator-data.js so the web part and the website always answer the\n'
  + '   same question the same way. */\n'
  + '\n'
  + 'export type FineRow = [\n'
  + '  string,  /* etid     */\n'
  + '  string,  /* company  */\n'
  + '  string,  /* country  */\n'
  + '  number,  /* year     */\n'
  + '  number,  /* fine     */\n'
  + '  number,  /* turnover */\n'
  + '  string,  /* type     */\n'
  + '  string,  /* sector   */\n'
  + '  string[],/* articles */\n'
  + '  string,  /* tier     */  /* "2%" or "4%", as the source records it */\n'
  + '  number,  /* conf     */\n'
  + '  number,  /* fin      */\n'
  + '  string,  /* tyear    */\n'
  + '  string,  /* tbasis   */\n'
  + '  string,  /* tsource  */\n'
  + '  number   /* ep       */\n'
  + '];\n'
  + '\n'
  + 'export interface FineType {\n'
  + '  code: string;\n'
  + '  label: string;\n'
  + '  note: string;\n'
  + '  thin?: boolean;\n'
  + '}\n'
  + '\n'
  + 'export const FINE_FIELDS: string[] = ' + JSON.stringify(FINE_FIELDS) + ';\n'
  + '\n'
  + 'export const FINE_ROWS: FineRow[] = [\n';

out += FINE_ROWS.map(function (r) { return JSON.stringify(r); }).join(',\n') + '\n';
out += '];\n\n';
out += 'export const ARTICLE_NAMES: { [n: string]: string } = ' + JSON.stringify(ARTICLE_NAMES, null, 2) + ';\n\n';
out += 'export const FINE_TYPES: FineType[] = [\n';
out += FINE_TYPES.map(function (t) {
  return '  {\n'
    + '    code: ' + q(t.code) + ',\n'
    + '    label: ' + q(t.label) + ',\n'
    + (t.thin ? '    thin: true,\n' : '')
    + '    note: ' + q(t.note) + '\n'
    + '  }';
}).join(',\n') + '\n';
out += '];\n\n';
out += 'export const FINE_SECTORS: string[] = ' + JSON.stringify(FINE_SECTORS, null, 2) + ';\n';

/* The site copy and the site prose both ban the em dash. Catch it here rather
   than in review. The character is written as an escape so this file does not
   contain one either. */
if (out.indexOf(String.fromCharCode(0x2014)) !== -1) {
  fail('an em dash reached the generated file');
}

fs.writeFileSync(outPath, out);
console.log('wrote ' + outPath);
console.log('  ' + FINE_ROWS.length + ' decisions, ' + FINE_TYPES.length + ' violation types, '
  + FINE_SECTORS.length + ' sectors, ' + Object.keys(ARTICLE_NAMES).length + ' article names');
